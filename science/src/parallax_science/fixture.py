"""Deterministic SIMULATED fixture for integration tests and UI development.

It imitates the SPHEREx Spectral Image HDU layout (IMAGE/FLAGS/VARIANCE) at a small size.
It is not a real sky region and contains no real astronomical signal.
"""

from __future__ import annotations

import itertools
import json
from pathlib import Path

import numpy as np
from astropy.io import fits
from astropy.wcs import WCS

from parallax_science import __version__
from parallax_science.cache import cache_key
from parallax_science.config import CompatibilityTolerances
from parallax_science.display import STRETCH_NAME, asinh_stretch, write_png_gray
from parallax_science.models import (
    SCHEMA_VERSION,
    Assets,
    Dataset,
    Epoch,
    GeneratedBy,
    Image,
    Manifest,
    Observation,
    Provenance,
    Quality,
    Spectral,
    Target,
)
from parallax_science.validation import assess_compatibility

MANIFEST_ID = "synthetic-fixture-001"
SEED = 2026
SIZE = 64
PIXEL_SCALE_ARCSEC = 6.2  # SPHEREx nominal pixel scale
CENTER = (180.0, 0.0)  # arbitrary; flagged as simulated everywhere
NOISE = 0.05
BACKGROUND = 1.0
# (observation suffix, MJD, detector, center wavelength um, mover pixel x, y)
EPOCHS = [
    ("e1", 61000.00, 3, 2.000, 20.0, 30.0),
    ("e2", 61000.25, 3, 2.005, 23.0, 31.0),
    ("e3", 61000.50, 4, 3.000, 26.0, 32.0),  # different detector: must be incompatible
]
NOTICE = (
    "SIMULATED DATA. Synthetic star field generated by parallax_science.fixture for software "
    "testing. It is not a SPHEREx observation, not a real sky region, and the injected moving "
    "source is not an astronomical object."
)


def _wcs() -> WCS:
    w = WCS(naxis=2)
    w.wcs.ctype = ["RA---TAN", "DEC--TAN"]
    w.wcs.crval = list(CENTER)
    w.wcs.crpix = [(SIZE + 1) / 2, (SIZE + 1) / 2]
    w.wcs.cdelt = [-PIXEL_SCALE_ARCSEC / 3600.0, PIXEL_SCALE_ARCSEC / 3600.0]
    w.wcs.cunit = ["deg", "deg"]
    w.wcs.radesys = "ICRS"
    return w


def _gaussian(yy: np.ndarray, xx: np.ndarray, x: float, y: float, flux: float) -> np.ndarray:
    sigma = 0.9  # px; SPHEREx PSFs are undersampled at 6.2"
    return (flux / (2 * np.pi * sigma**2)) * np.exp(
        -((xx - x) ** 2 + (yy - y) ** 2) / (2 * sigma**2)
    )


def build(out_root: Path) -> Manifest:
    """Write FITS + PNG assets under out_root/fixtures/<id>/ and return the manifest."""
    rng = np.random.default_rng(SEED)
    rel_dir = f"fixtures/{MANIFEST_ID}"
    (out_root / rel_dir).mkdir(parents=True, exist_ok=True)
    w = _wcs()
    wcs_cards = {k: v for k, v in w.to_header().items() if k not in ("COMMENT", "HISTORY")}
    yy, xx = np.mgrid[0:SIZE, 0:SIZE].astype(np.float32)
    stars = [
        (rng.uniform(4, SIZE - 4), rng.uniform(4, SIZE - 4), 10 ** rng.uniform(0, 1.5))
        for _ in range(25)
    ]

    observations = []
    for suffix, mjd, detector, wl, mx, my in EPOCHS:
        image = np.full((SIZE, SIZE), BACKGROUND, dtype=np.float32)
        for sx, sy, flux in stars:
            image += _gaussian(yy, xx, sx, sy, flux)
        image += _gaussian(yy, xx, mx, my, 8.0)
        image += rng.normal(0.0, NOISE, image.shape).astype(np.float32)

        oid = f"{MANIFEST_ID}.{suffix}"
        fits_rel, png_rel = f"{rel_dir}/{suffix}.fits", f"{rel_dir}/{suffix}.png"
        header = w.to_header()
        header["BUNIT"] = "MJy/sr"
        header["SIMULATE"] = (True, "Synthetic data, not a SPHEREx observation")
        header["MJD-AVG"] = (mjd, "Simulated mid-exposure MJD (UTC)")
        header["DETECTOR"] = detector
        fits.HDUList(
            [
                fits.PrimaryHDU(header=fits.Header([("SIMULATE", True), ("ORIGIN", "PARALLAX")])),
                fits.ImageHDU(image, header=header, name="IMAGE"),
                fits.ImageHDU(np.zeros_like(image, dtype=np.int32), name="FLAGS"),
                fits.ImageHDU(np.full_like(image, NOISE**2), name="VARIANCE"),
            ]
        ).writeto(out_root / fits_rel, overwrite=True)
        # FITS origin is bottom-left; PNG rows run top-down.
        write_png_gray(out_root / png_rel, asinh_stretch(image)[::-1])

        observations.append(
            Observation(
                observation_id=oid,
                data_kind="simulated",
                epoch=Epoch(
                    mjd_mid=mjd, time_scale="utc", exposure_s=112.0, source_keyword="MJD-AVG"
                ),
                spectral=Spectral(
                    detector=detector,
                    wavelength_center_um=wl,
                    wavelength_min_um=wl * 0.99,
                    wavelength_max_um=wl * 1.01,
                    basis="simulated",
                ),
                image=Image(
                    width_px=SIZE,
                    height_px=SIZE,
                    pixel_scale_arcsec=PIXEL_SCALE_ARCSEC,
                    units="MJy/sr",
                    wcs=wcs_cards,
                ),
                quality=Quality(
                    flags_available=True,
                    variance_available=True,
                    masked_fraction=0.0,
                    notes=["Simulated Gaussian PSF and white noise; no artifacts modeled."],
                ),
                assets=Assets(
                    science_fits=fits_rel, display_png=png_rel, display_stretch=STRETCH_NAME
                ),
                provenance=Provenance(
                    source_url=None,
                    source_id=oid,
                    calibration_version="simulated-v1",
                    processing=f"parallax make-fixture (seed={SEED})",
                    cache_key=cache_key(oid, {"seed": SEED, "size": SIZE, "stretch": STRETCH_NAME}),
                ),
            )
        )

    tol = CompatibilityTolerances()
    comparisons = [
        assess_compatibility(a, b, tol) for a, b in itertools.combinations(observations, 2)
    ]
    return Manifest(
        schema_version=SCHEMA_VERSION,
        manifest_id=MANIFEST_ID,
        data_kind="simulated",
        title="Synthetic fixture: simulated three-epoch field",
        notice=NOTICE,
        target=Target(
            label="Synthetic field (not a real sky region)",
            ra_deg=CENTER[0],
            dec_deg=CENTER[1],
            radius_arcsec=SIZE * PIXEL_SCALE_ARCSEC / 2,
        ),
        dataset=Dataset(
            mission="SIMULATED",
            archive=None,
            collection=None,
            data_release=None,
            citation="Synthetic data generated by PARALLAX; no external source.",
            acknowledgement="Layout modeled on NASA SPHEREx Spectral Images distributed by IRSA.",
        ),
        observations=observations,
        comparisons=comparisons,
        candidates=[],
        generated_by=GeneratedBy(
            tool="parallax-science", version=__version__, command="parallax make-fixture"
        ),
    )


def write_manifest(manifest: Manifest, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(manifest.model_dump(mode="json"), indent=2, ensure_ascii=False)
    path.write_text(text + "\n", encoding="utf-8", newline="\n")
